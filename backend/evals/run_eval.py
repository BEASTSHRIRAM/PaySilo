"""Intake eval runner (Issue #15).

Scores PaySilo's intake parsers against the messy-fixture corpus in
``corpus.json`` (24 payroll emails / CSVs with expected pay lines) and
writes ``REPORT.md`` next to this file.

What is scored:
- the **deterministic parser** (``app.agents.intake.parse_text_input``) —
  always run; it is the fallback that demos and tests rely on.
- the **LLM path** (Claude via ``parse_intake``) — only when
  ``ANTHROPIC_API_KEY`` is set. On this machine no key exists, so the
  report marks the LLM column "not run — no key" instead of inventing
  numbers.

Scoring, per case:
- employer: exact match, case-insensitive.
- funding: Decimal equality with the expected funding amount.
- pay line: an expected line counts as correct when a parsed line has
  the same name (case-insensitive), amount (Decimal equality) and
  currency. Extra parsed lines are reported as spurious.
- case: fully correct only when employer, funding and every expected
  line are correct and there are no spurious lines.

Run from ``backend/``:  ``uv run python evals/run_eval.py``
"""

from __future__ import annotations

import json
import os
import sys
from decimal import Decimal
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))  # backend/, so `app` imports work

from app.agents.intake import parse_intake, parse_text_input  # noqa: E402


def _norm(name: str) -> str:
    return " ".join(name.casefold().split())


def score_case(parsed, expected: dict) -> dict:
    employer_name, funding, lines = parsed
    employer_ok = _norm(employer_name) == _norm(expected["employer_name"])
    funding_ok = Decimal(funding) == Decimal(expected["funding_usd"])
    remaining = list(lines)
    correct = 0
    for want in expected["pay_lines"]:
        hit = next((l for l in remaining
                    if _norm(l.name) == _norm(want["name"])
                    and Decimal(l.amount) == Decimal(want["amount"])
                    and l.currency.upper() == want["currency"].upper()), None)
        if hit is not None:
            correct += 1
            remaining.remove(hit)
    return {"employer_ok": employer_ok, "funding_ok": funding_ok,
            "lines_correct": correct, "lines_expected": len(expected["pay_lines"]),
            "spurious": len(remaining),
            "parsed": {"employer_name": employer_name, "funding_usd": str(funding),
                       "pay_lines": [{"name": l.name, "amount": str(l.amount), "currency": l.currency}
                                     for l in lines]}}


def pct(n: int, d: int) -> str:
    return f"{(100.0 * n / d):.1f}%" if d else "n/a"


def main() -> int:
    corpus = json.loads((HERE / "corpus.json").read_text())
    llm_available = bool(os.environ.get("ANTHROPIC_API_KEY"))

    rows, totals = [], {"employer": 0, "funding": 0, "lines_c": 0, "lines_e": 0, "cases": 0, "spurious": 0}
    llm_totals = {"lines_c": 0, "cases": 0}
    for case in corpus:
        det = score_case(parse_text_input(case["input"]), case["expected"])
        full = (det["employer_ok"] and det["funding_ok"]
                and det["lines_correct"] == det["lines_expected"] and det["spurious"] == 0)
        totals["employer"] += det["employer_ok"]
        totals["funding"] += det["funding_ok"]
        totals["lines_c"] += det["lines_correct"]
        totals["lines_e"] += det["lines_expected"]
        totals["cases"] += full
        totals["spurious"] += det["spurious"]
        llm_cell = "not run — no key"
        if llm_available:
            got = score_case(parse_intake(case["input"]), case["expected"])
            llm_full = (got["employer_ok"] and got["funding_ok"]
                        and got["lines_correct"] == got["lines_expected"] and got["spurious"] == 0)
            llm_totals["lines_c"] += got["lines_correct"]
            llm_totals["cases"] += llm_full
            llm_cell = f"{got['lines_correct']}/{got['lines_expected']} lines"
        rows.append((case, det, full, llm_cell))

    n = len(corpus)
    lines = [
        "# Intake Eval Report",
        "",
        "Generated by `backend/evals/run_eval.py` against `backend/evals/corpus.json` "
        f"({n} messy payroll fixtures: emails and CSVs as raw text).",
        "",
        "## Summary",
        "",
        "| Metric | Deterministic parser | LLM (Claude) |",
        "|---|---|---|",
        f"| Pay-line accuracy | {totals['lines_c']}/{totals['lines_e']} ({pct(totals['lines_c'], totals['lines_e'])}) | "
        + (f"{llm_totals['lines_c']}/{totals['lines_e']} ({pct(llm_totals['lines_c'], totals['lines_e'])}) |" if llm_available else "not run — no key |"),
        f"| Fully-correct cases | {totals['cases']}/{n} ({pct(totals['cases'], n)}) | "
        + (f"{llm_totals['cases']}/{n} ({pct(llm_totals['cases'], n)}) |" if llm_available else "not run — no key |"),
        f"| Employer accuracy | {totals['employer']}/{n} ({pct(totals['employer'], n)}) | — |",
        f"| Funding accuracy | {totals['funding']}/{n} ({pct(totals['funding'], n)}) | — |",
        f"| Spurious parsed lines | {totals['spurious']} | — |",
        "",
        "The deterministic parser only understands lines beginning with "
        "`employer:` / `fund USD <amount>` / `pay <name> <CCY> <amount>`. "
        "Fixtures in other shapes (plain CSV rows, polite prefixes, amounts "
        "in words, European decimals, bullet lists) are included on purpose: "
        "they measure exactly where the fallback stops and the LLM reader "
        "is needed. No LLM numbers are reported without a key — set "
        "`ANTHROPIC_API_KEY` and re-run to fill the LLM column.",
        "",
        "## Per-case results (deterministic parser)",
        "",
        "| Case | Kind | Employer | Funding | Pay lines | Verdict |",
        "|---|---|---|---|---|---|",
    ]
    for case, det, full, _llm in rows:
        lines.append(
            f"| {case['id']} | {case['kind']} | {'ok' if det['employer_ok'] else 'MISS'} | "
            f"{'ok' if det['funding_ok'] else 'MISS'} | {det['lines_correct']}/{det['lines_expected']} | "
            f"{'PASS' if full else 'partial' if det['lines_correct'] else 'FAIL'} |")
    lines += ["", "## Notes", "",
              "- A missed or misread line never moves money on its own: intake output is "
              "matched against the employer's own contractor directory, priced by "
              "deterministic policy, and still pauses for a TAP-signed human approval.",
              "- Corpus ground truth is the payroll as a human would read it; "
              "`Unknown Employer` is the expected employer for fixtures with no employer header.",
              ""]
    (HERE / "REPORT.md").write_text("\n".join(lines))
    print(f"cases={n} line_accuracy={totals['lines_c']}/{totals['lines_e']} "
          f"full_cases={totals['cases']}/{n} employer={totals['employer']}/{n} "
          f"funding={totals['funding']}/{n} spurious={totals['spurious']} "
          f"llm={'run' if llm_available else 'not run — no key'}")
    print(f"wrote {HERE / 'REPORT.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
